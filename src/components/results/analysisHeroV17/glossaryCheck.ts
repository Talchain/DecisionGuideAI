/**
 * Canonical glossary check for AnalysisHeroV17.
 *
 * ONE matcher shared between:
 *   - Production code (rowRanking.ts, buildAnalysisHeroViewModel.ts)
 *     uses `containsBannedTerm` to gate label interpolation. When a
 *     user-supplied label trips the matcher, generated copy falls back
 *     to a glossary-safe phrase — we never rewrite user data, only the
 *     generated copy that names it.
 *   - Test scanner (src/test/glossaryBannedTerms.ts) re-exports the
 *     canonical list so the broad scan tests for the same banned terms
 *     the production fallback gates against. This means production and
 *     tests are kept in lock-step: a term that ships in production
 *     output WILL be flagged by the test scanner, and vice versa.
 *
 * Source for the list: docs/investigations/analysis-hero-v17.md §12 +
 * the Olumi Communication Glossary v1.
 *
 * (Per docs/brief-analysis-hero-v17-implementation.md §3 step 8, the
 * production hero must not import the test asset. The opposite direction
 * — test importing from production — is the correct dependency arrow:
 * tests verify production behaviour against a shared truth.)
 */

/**
 * Canonical list — every term that must not appear in user-facing copy
 * generated by AnalysisHeroV17. Multi-word entries match literally
 * (case-insensitive). Single-word entries are word-boundary wrapped in
 * the regex builder, so e.g. "graph" in "telegraph" does not false-positive.
 */
export const ANALYSIS_HERO_BANNED_TERMS = [
  // §1 Leading option
  'recommend', 'recommended', 'recommendation', 'winner', 'winning', 'best choice',
  // §2 Win probability
  'wins', 'win rate', 'chance of winning', 'probability of success',
  // §3 Stability
  'recommendation stability', 'robustness score', 'confidence score',
  // §4 Sensitivity
  'elasticity', 'factor sensitivity', 'sensitivity score', 'beta coefficient',
  // §5 Confidence (edge)
  'exists probability', 'belief exists', 'epistemic uncertainty',
  // §6 Effect strength
  'strength mean', 'b coefficient', 'regression weight',
  // §8 Value of information
  'EVPI', 'expected value of perfect information', 'VOI', 'voi ranking',
  // §10 Fragile edge
  'fragile edge', 'switch probability', 'marginal switch probability',
  // §11 Simulation
  'stochastic', 'random sampling',
  // §15 Causal model
  'graph', 'DAG', 'SCM', 'structural causal model', 'nodes and edges',
  // §17 Decision readiness
  'blocked', 'cannot run', 'fix issues', 'fix issue', 'required actions', 'validation errors',
  // §18 Bias
  'you have a bias', 'bias detected', 'you are exhibiting',
  // §19 Uncertainty
  'prior range', 'posterior', 'variance',
  // Internal terms
  'headline_type', 'observed state', 'observed_state', 'canonical_state',
  'exists_probability', 'voi', 'attribution_stability', 'rank_flip_rate',
  'model_critiques', 'strength_mean', 'strength_std', 'intervention',
  'bootstrap', 'perturbation', 'ISL', 'PLoT', 'CEE',
] as const

let cachedRegex: RegExp | null = null

/**
 * Build a single regex from the banned list. Single-word entries are
 * word-boundary wrapped; multi-word entries match literally. Lazy-cached.
 */
function bannedTermRegex(): RegExp {
  if (cachedRegex) return cachedRegex
  const escaped = ANALYSIS_HERO_BANNED_TERMS.map(t =>
    t.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'),
  )
  const patterns = escaped.map(t =>
    /^[a-z][a-z_]*$/i.test(t) ? `\\b${t}\\b` : t,
  )
  cachedRegex = new RegExp(`(?:${patterns.join('|')})`, 'i')
  return cachedRegex
}

/**
 * Production-side gate. Returns true if `text` contains any banned term.
 * Used by row builders and the VM orchestrator to decide whether to
 * interpolate a user-supplied label or fall back to a generic phrase.
 */
export function containsBannedTerm(text: string | null | undefined): boolean {
  if (!text) return false
  return bannedTermRegex().test(text)
}

/**
 * Returns the first banned term found in `text`, or null. Used by tests
 * to produce a helpful failure message.
 */
export function findBannedTerm(text: string | null | undefined): string | null {
  if (!text) return null
  const m = bannedTermRegex().exec(text)
  return m ? m[0] : null
}

/**
 * Glossary-safe label interpolation helper. If `raw` trips the matcher,
 * return `fallback`. Otherwise return `raw` unchanged. Important: this
 * never rewrites user data — `raw` is only consumed in GENERATED copy
 * (chat prompts, key questions, reasons). The user's original label
 * still appears verbatim in row titles and inspector views.
 */
export function safeInterpolatedLabel(raw: string | null | undefined, fallback: string): string {
  if (!raw) return fallback
  if (containsBannedTerm(raw)) return fallback
  return raw
}
