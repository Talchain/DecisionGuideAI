/**
 * The View's TypeScript types, generated from olumi-core's published JSON Schema (`schema/view.v3.json`, vendored as
 * src/olumiView/view.v3.json; the page reads olumi.view/3, asked for with ?schema=3). The client never writes the View's shape by hand: change core's schema, re-vendor it, and run
 *   node scripts/olumi-view/gen-types.mjs
 * A spec (src/olumiView/__tests__/client.spec.ts) fails when the committed types differ from what this prints.
 *
 * Only the keywords core's schema uses: type, properties, required, additionalProperties, items, anyOf, oneOf, const, enum.
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const KEYWORDS = new Set(['$schema', 'type', 'properties', 'required', 'additionalProperties', 'items', 'anyOf', 'oneOf', 'const', 'enum', 'propertyNames'])

export function typeOf(s, pad = '') {
  // An empty schema (`{}`, core's `accepted[].prior` and `.value`: any JSON) accepts anything: `unknown`, never a guess at its shape.
  if (Object.keys(s).length === 0) return 'unknown'
  for (const k of Object.keys(s)) if (!KEYWORDS.has(k)) throw new Error(`unsupported schema keyword: ${k}`)
  if ('const' in s) return JSON.stringify(s.const)
  if (s.enum) return s.enum.map((x) => JSON.stringify(x)).join(' | ')
  if (s.anyOf || s.oneOf) return (s.anyOf ?? s.oneOf).map((x) => typeOf(x, pad)).join(' | ')
  if (Array.isArray(s.type)) return s.type.map((t) => typeOf({ ...s, type: t }, pad)).join(' | ')
  switch (s.type) {
    case 'string': return 'string'
    case 'number': case 'integer': return 'number'
    case 'boolean': return 'boolean'
    case 'null': return 'null'
    case 'array': return `Array<${typeOf(s.items, pad)}>`
    case 'object': {
      const req = new Set(s.required ?? []), inner = `${pad}  `
      const rows = Object.entries(s.properties ?? {}).map(([k, v]) => `${inner}${k}${req.has(k) ? '' : '?'}: ${typeOf(v, inner)}`)
      if (s.propertyNames) typeOf(s.propertyNames, inner)
      if (s.additionalProperties && typeof s.additionalProperties === 'object') rows.push(`${inner}[key: string]: ${typeOf(s.additionalProperties, inner)}`)
      return rows.length ? `{\n${rows.join('\n')}\n${pad}}` : 'Record<string, never>'
    }
    default: throw new Error(`unsupported schema type: ${JSON.stringify(s.type)}`)
  }
}

export function generate(schema) {
  return [
    '// GENERATED by scripts/olumi-view/gen-types.mjs from src/olumiView/view.v3.json (olumi-core schema/view.v3.json). Do not edit.',
    `export type View = ${typeOf(schema)}`,
    '',
  ].join('\n')
}

const here = path.dirname(fileURLToPath(import.meta.url)), root = path.resolve(here, '../..')
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const schema = JSON.parse(fs.readFileSync(path.join(root, 'src/olumiView/view.v3.json'), 'utf8'))
  fs.writeFileSync(path.join(root, 'src/olumiView/types.ts'), generate(schema))
}
