#!/usr/bin/env node
// scripts/generate-flag-env.mjs
// =============================================================================
// Generates `src/lib/flagEnv.ts` — the NAMED, LITERAL env reads that replace
// flagFactory's `{ ...import.meta.env }` spread.
// =============================================================================
//
// WHY THIS EXISTS
// ---------------
// Vite statically replaces `import.meta.env.VITE_X` with that one value, but it
// cannot narrow a BARE `import.meta.env` reference (a spread, an assignment, a
// default parameter). At every bare reference it inlines the ENTIRE env object —
// every `VITE_*` the deploy defines, with its value — into that chunk.
//
// Measured on 2026-07-28 (credential-free synthetic env): six such sites existed,
// and a variable referenced NOWHERE in `src/` was still baked into five chunks.
// Exposure was driven by what the deploy SET, not by what the code READ.
//
// flagFactory cannot simply be rewritten to named reads by hand, because it looks
// values up DYNAMICALLY (`envSnapshot[config.envKey]`) for ~70 flags. So the named
// reads are GENERATED from the same source of truth the flags system already uses.
//
// DERIVED, NOT MIRRORED (CLAUDE.md trap 12)
// -----------------------------------------
// The key set is derived from:
//   1. `src/flags.ts` FLAGS_CONFIG — via `deriveDeclaredFlags`, the SAME AST walker
//      `tools/ci-guards/flag-deployment-drift.mjs` uses. Adding a flag there and
//      re-running this generator is the whole workflow.
//   2. `netlify.toml` — every `VITE_FEATURE_*` / `VITE_ENABLE_*` the repo declares.
//      These are not all declared flags, but `exportBundle.ts`'s debug snapshot
//      enumerated them out of the full env, so they must stay reachable.
//
// `--check` reds if the committed file has drifted from what this would generate,
// so the generated file can never silently fall behind `src/flags.ts`. That is the
// fail-loud requirement: a flag whose key is missing from the snapshot would
// silently resolve to its defaultValue — a SILENT FLAG FLIP, the exact class of
// defect trap 12 exists to prevent.
//
// VITE BUILT-INS ARE INCLUDED DELIBERATELY, AND `BASE_URL` MUST STAY FIRST.
// `tools/ci-guards/flag-deployment-drift.mjs :: extractDeployedEnv` locates the
// deployed env object by anchoring on `BASE_URL:` and walking BACK to the opening
// brace (it aborts on an intervening `}` or `;`). Keeping BASE_URL as the first
// property means `pnpm flags:check` keeps reading the deployed flag values with NO
// change to that tool. `MODE`/`DEV`/`PROD`/`SSR` are Vite build metadata, not
// secrets, and `flagFactory.spec.ts` pins a lookup of `MODE`.
// =============================================================================

import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { deriveDeclaredFlags, parseNetlifyEnv } from '../tools/ci-guards/flag-deployment-drift.mjs'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const FLAGS_TS = path.join(ROOT, 'src/flags.ts')
const NETLIFY_TOML = path.join(ROOT, 'netlify.toml')
const OUT = path.join(ROOT, 'src/lib/flagEnv.ts')

/** Vite build metadata. Not secrets. BASE_URL MUST be first — see header. */
const VITE_BUILTINS = ['BASE_URL', 'MODE', 'DEV', 'PROD', 'SSR']

/** Every `VITE_FEATURE_*` / `VITE_ENABLE_*` declared anywhere in netlify.toml. */
export function deriveNetlifyFeatureKeys(tomlText) {
  const { build, staging } = parseNetlifyEnv(tomlText)
  return Object.keys({ ...build, ...staging })
    .filter((k) => k.startsWith('VITE_FEATURE_') || k.startsWith('VITE_ENABLE_'))
    .sort()
}

export function deriveKeys({ flagsSource, netlifySource }) {
  const { flags, unparseable } = deriveDeclaredFlags(flagsSource, 'src/flags.ts')
  if (unparseable.length > 0) {
    throw new Error(
      `src/flags.ts has ${unparseable.length} UNPARSEABLE flag declaration(s); refusing to generate a ` +
        `snapshot that would silently omit them:\n  ` +
        unparseable.map((u) => `${u.name}: ${u.reason}`).join('\n  '),
    )
  }
  if (flags.length === 0) throw new Error('Derived ZERO flags from src/flags.ts — refusing to generate an empty snapshot.')

  const declared = flags.map((f) => f.envKey)
  const netlifyFeature = deriveNetlifyFeatureKeys(netlifySource)
  const vite = [...new Set([...declared, ...netlifyFeature])].sort()
  return { builtins: VITE_BUILTINS, vite, declaredCount: declared.length, netlifyCount: netlifyFeature.length }
}

export function renderModule({ builtins, vite, declaredCount, netlifyCount }) {
  const line = (k) => `  ${k}: import.meta.env?.${k},`
  return `/**
 * AUTO-GENERATED FILE — DO NOT EDIT BY HAND.
 *
 * Generated by: scripts/generate-flag-env.mjs
 * Regenerate:   pnpm run generate:flag-env
 * Verify:       pnpm run ci:guard:flag-env   (reds on drift from src/flags.ts / netlify.toml)
 *
 * WHAT THIS IS. The named, literal env reads that back \`flagFactory\`'s snapshot.
 * It replaced \`envSnapshot = { ...import.meta.env }\`, which Vite could not
 * statically narrow — so it inlined EVERY \`VITE_*\` the deploy defines, with its
 * value, into the flags chunk. Each entry below is narrowed by Vite to that one
 * value, so the chunk now carries only keys the app actually declares.
 *
 * DERIVED, NOT HAND-LISTED: ${declaredCount} flag keys from \`src/flags.ts\` FLAGS_CONFIG
 * (via the same AST walker \`pnpm flags:check\` uses) + ${netlifyCount} \`VITE_FEATURE_*\`/
 * \`VITE_ENABLE_*\` keys declared in \`netlify.toml\`. Adding a flag and re-running the
 * generator is the whole workflow; \`--check\` reds if this file falls behind.
 *
 * SEMANTICS ARE UNCHANGED from the spread. A key that is unset at build time reads
 * \`undefined\` here, where previously it was ABSENT from the spread object. Both
 * \`makeFlag\` (falls through to \`defaultValue\`) and \`diagnoseFlagState\`
 * (\`?? null\`) treat those identically.
 *
 * \`BASE_URL\` MUST STAY FIRST — \`tools/ci-guards/flag-deployment-drift.mjs\`
 * anchors on it and walks BACK to the opening brace to read deployed flag values.
 */

/* eslint-disable */
export const FLAG_ENV: Record<string, unknown> = {
${builtins.map(line).join('\n')}
${vite.map(line).join('\n')}
}
`
}

function main() {
  const flagsSource = readFileSync(FLAGS_TS, 'utf8')
  const netlifySource = readFileSync(NETLIFY_TOML, 'utf8')
  const rendered = renderModule(deriveKeys({ flagsSource, netlifySource }))

  if (process.argv.includes('--check')) {
    let current = null
    try { current = readFileSync(OUT, 'utf8') } catch { /* missing */ }
    if (current !== rendered) {
      console.error(
        `\n❌ src/lib/flagEnv.ts is STALE.\n\n` +
          `   It is generated from src/flags.ts + netlify.toml. One of those changed without\n` +
          `   regenerating, so a flag key may be MISSING from the snapshot — which would make\n` +
          `   that flag silently resolve to its defaultValue instead of its env value.\n\n` +
          `   Fix:  pnpm run generate:flag-env\n`,
      )
      process.exit(1)
    }
    console.log('✅ src/lib/flagEnv.ts is up to date with src/flags.ts + netlify.toml')
    return
  }

  writeFileSync(OUT, rendered)
  console.log(`✅ wrote ${path.relative(ROOT, OUT)}`)
}

if (import.meta.url === `file://${process.argv[1]}`) main()
