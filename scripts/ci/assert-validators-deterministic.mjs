#!/usr/bin/env node
// scripts/ci/assert-validators-deterministic.mjs
// =============================================================================
// The generated Ajv validators must be a PURE FUNCTION of their inputs.
// =============================================================================
//
// WHY THIS EXISTS
// ---------------
// `npm run build` is `generate:validators && vite build`, and
// `src/generated/validators.js` is COMMITTED. It has to be: `src/poc/io/validate.ts`
// imports it, and that import is reached from vitest
// (`src/poc/io/__tests__/schema.spec.ts`) where no generation step runs. The file
// exists specifically to avoid a CSP-violating runtime `new Function`, so
// gitignoring it and generating on demand is not available.
//
// Committed + regenerated-on-every-build means any non-determinism in the
// generator dirties the working tree on every build. Until 2026-08-29 the
// emitted header carried `Generated at: <ISO clock>`, so it did exactly that:
// a clean checkout, one `pnpm run build`, and `git status` reported
// `M src/generated/validators.js` with a diff whose entire content was the
// timestamp. Reproduced on three independent fresh blobless clones.
//
// That is not cosmetic. `git status` is this estate's "did I change anything"
// signal during verification — mutation harnesses assert a clean tree before and
// after every mutant (CLAUDE.md traps 9g/9h) — and a build that dirties the tree
// on its own poisons that signal and invites the churn into unrelated commits.
//
// WHAT IT CHECKS, IN ORDER
// ------------------------
//   0. SELF-TEST. Prove the comparator and the vacuity detector discriminate,
//      in THIS Node, on THIS run, before any verdict is issued.
//   1. NON-VACUITY. Both generated outputs must be non-trivial — a byte floor
//      AND required markers. ⚠ THIS IS LOAD-BEARING: two empty extractions
//      compare equal and "agree" perfectly. That exact failure has bitten this
//      estate through shell quoting (CLAUDE.md: a `diff` of two empty files
//      exits 0 and reports LADDER-IDENTICAL). An absence/agreement probe with
//      no non-empty assertion proves nothing.
//   2. DETERMINISM. Run the generator TWICE into two throwaway directories and
//      require byte-identical output. This is the property that was violated.
//   3. FRESHNESS. The freshly generated bytes must equal the COMMITTED artefact.
//      This is what replaced the `Generated at:` stamp, and it is strictly
//      better: a stamp is a hand-maintained mirror that only claims freshness,
//      whereas this reds on real drift from ANY cause — a schema edit, an Ajv
//      upgrade, an options change — and it is derived, not written down.
//
// The generator is invoked as a real SUBPROCESS, the same entry point the build
// runs, rather than imported as a refactored library. What is proven
// deterministic is therefore what the build actually executes.
//
// ⚠ WIRED INTO THE `build` JOB OF "Staging Gate", NOT ONLY INTO ci.yml.
// `staging` branch protection requires exactly ONE check, whose `needs` list is
// [tsc, typecheck-selftest, vitest, vitest-summary, build]. Nothing in ci.yml is
// required, so a guard living only there would advise and never block — the same
// shape as the sibling bundle-credentials and logger-emits guards, wired the
// same way for the same reason.
//   Derived 2026-08-29:
//     gh api repos/Talchain/DecisionGuideAI/branches/staging/protection \
//       --jq '.required_status_checks.contexts'   → ["Staging Gate"]
// Re-derive before assuming this is still where the blocking happens.
//
// Runnable bare: `node scripts/ci/assert-validators-deterministic.mjs`.
// =============================================================================

import { mkdtempSync, readFileSync, rmSync, existsSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { spawnSync } from 'node:child_process'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

export const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..')

/** The generator under test — the same script `npm run build` invokes. */
export const GENERATOR = path.join(ROOT, 'scripts', 'generate-validators.mjs')

/** Where the committed artefacts live. */
export const COMMITTED_DIR = path.join(ROOT, 'src', 'generated')

/**
 * What a non-trivial output looks like, per artefact.
 *
 * Both a byte floor AND markers, deliberately. A floor alone passes on 5 kB of
 * the wrong thing; markers alone pass on a header with the body truncated away.
 * The markers are chosen to be stable across Ajv versions: they are the schema
 * `$id` and the exported symbol, not Ajv's internal `validate10` numbering.
 */
export const ARTEFACTS = [
  {
    file: 'validators.js',
    minBytes: 4000,
    markers: ['export const validateSamState', 'poc/samState.schema.v1', 'schemaVersion'],
  },
  {
    file: 'validators.d.ts',
    minBytes: 200,
    markers: ['export declare const validateSamState', 'interface SamState'],
  },
]

/**
 * Thrown when an output is missing, empty, too small, or lacks a required marker.
 *
 * Never swallow this and never let it degrade into a pass. A zero-byte or absent
 * output is exactly the shape a failed or skipped generation takes, and two of
 * them compare EQUAL — which is the whole reason this error class exists.
 */
export class VacuousOutputError extends Error {
  constructor(message) {
    super(message)
    this.name = 'VacuousOutputError'
  }
}

/**
 * Assert one generated artefact is real output, not a vacuous stand-in.
 * @throws {VacuousOutputError}
 */
export function assertNonTrivial(label, text, spec) {
  if (typeof text !== 'string') {
    throw new VacuousOutputError(`${label}: not a string (got ${typeof text}) — generation did not produce readable output.`)
  }
  if (text.trim().length === 0) {
    throw new VacuousOutputError(`${label}: EMPTY (${text.length} bytes, no non-whitespace). Two empty outputs compare equal — this must never be read as agreement.`)
  }
  const bytes = Buffer.byteLength(text, 'utf8')
  if (bytes < spec.minBytes) {
    throw new VacuousOutputError(`${label}: only ${bytes} bytes, below the ${spec.minBytes}-byte floor for ${spec.file}. Real output is an order of magnitude larger; this is a truncated or failed generation.`)
  }
  const missing = spec.markers.filter((m) => !text.includes(m))
  if (missing.length > 0) {
    throw new VacuousOutputError(`${label}: missing required marker(s) ${missing.map((m) => JSON.stringify(m)).join(', ')} — ${bytes} bytes of something, but not a generated validator module.`)
  }
  return bytes
}

/**
 * Byte-compare two outputs, reporting WHERE they diverge.
 *
 * Returns `{ identical, index, aContext, bContext }`. Callers must have run
 * `assertNonTrivial` on both sides first: this function cannot tell agreement
 * from mutual absence, and is not supposed to.
 */
export function compare(a, b) {
  if (a === b) return { identical: true, index: -1, aContext: '', bContext: '' }
  const limit = Math.min(a.length, b.length)
  let i = 0
  while (i < limit && a[i] === b[i]) i++
  const from = Math.max(0, i - 60)
  return {
    identical: false,
    index: i,
    aContext: a.slice(from, i + 60),
    bContext: b.slice(from, i + 60),
  }
}

/** Run the generator into `outDir` as a subprocess. Throws on a non-zero exit. */
export function generateInto(outDir, { generator = GENERATOR, cwd = ROOT } = {}) {
  const result = spawnSync(process.execPath, [generator, '--out-dir', outDir], {
    cwd,
    encoding: 'utf8',
    // The generator prints progress; keep it out of the guard's own output
    // unless it fails, where it is the most useful thing on screen.
    stdio: ['ignore', 'pipe', 'pipe'],
  })
  if (result.error) {
    throw new Error(`generator failed to spawn: ${result.error.message}`)
  }
  if (result.status !== 0) {
    throw new Error(`generator exited ${result.status}\n--- stdout ---\n${result.stdout}\n--- stderr ---\n${result.stderr}`)
  }
  const out = {}
  for (const spec of ARTEFACTS) {
    const p = path.join(outDir, spec.file)
    if (!existsSync(p)) {
      throw new VacuousOutputError(`generator exited 0 but did not write ${spec.file} into ${outDir} — a silent no-op is not a pass.`)
    }
    out[spec.file] = readFileSync(p, 'utf8')
  }
  return out
}

/**
 * Prove the instrument is alive HERE, this run, before any verdict.
 *
 * A CONTRAST PAIR on each half. Either half alone proves nothing: a comparator
 * that calls everything identical passes the positive control, and one that
 * calls everything different passes the negative. Same for the vacuity detector.
 * @throws {Error} if any control disagrees.
 */
export function selfTest() {
  const spec = ARTEFACTS[0]
  const real = 'x'.repeat(spec.minBytes) + spec.markers.join('\n')

  // Comparator — must ACCEPT identical, must REJECT a one-byte divergence.
  if (!compare(real, real).identical) {
    throw new Error('selfTest: comparator called identical inputs different — instrument is dead.')
  }
  const drifted = compare(real, real + '\n// drift')
  if (drifted.identical) {
    throw new Error('selfTest: comparator called differing inputs identical — instrument cannot discriminate.')
  }

  // ⚠ THE CONTROL THAT MATTERS MOST. Two empty strings are byte-identical, so a
  // comparator alone reports perfect agreement about nothing at all. The vacuity
  // gate is what stops that being read as a pass.
  if (!compare('', '').identical) {
    throw new Error('selfTest: expected two empty strings to compare equal — the premise this guard defends against.')
  }
  let emptyRejected = false
  try {
    assertNonTrivial('selfTest/empty', '', spec)
  } catch (e) {
    emptyRejected = e instanceof VacuousOutputError
  }
  if (!emptyRejected) {
    throw new Error('selfTest: vacuity gate ACCEPTED an empty output. Two empty outputs would agree and the guard would pass by testing nothing.')
  }

  // Vacuity gate — must REJECT short, must REJECT marker-less, must ACCEPT real.
  let shortRejected = false
  try {
    assertNonTrivial('selfTest/short', 'tiny', spec)
  } catch (e) {
    shortRejected = e instanceof VacuousOutputError
  }
  if (!shortRejected) {
    throw new Error('selfTest: vacuity gate accepted output below the byte floor.')
  }

  let markerlessRejected = false
  try {
    assertNonTrivial('selfTest/markerless', 'y'.repeat(spec.minBytes + 100), spec)
  } catch (e) {
    markerlessRejected = e instanceof VacuousOutputError
  }
  if (!markerlessRejected) {
    throw new Error('selfTest: vacuity gate accepted output with no required markers.')
  }

  assertNonTrivial('selfTest/real', real, spec) // must NOT throw
}

/** CLI entry. Returns the process exit code (0 pass, 1 fail). */
export function run({ committedDir = COMMITTED_DIR, log = console.log, err = console.error } = {}) {
  const dirs = []
  try {
    selfTest()
    log('✅ self-test: comparator and vacuity gate both discriminate')

    // ── 1+2. Generate twice, into two throwaway directories ──────────────
    for (let i = 0; i < 2; i++) {
      dirs.push(mkdtempSync(path.join(tmpdir(), `validators-determinism-${i}-`)))
    }
    const runA = generateInto(dirs[0])
    const runB = generateInto(dirs[1])

    for (const spec of ARTEFACTS) {
      // NON-VACUITY FIRST, ALWAYS, ON BOTH SIDES. Never compare before this.
      const bytesA = assertNonTrivial(`run A / ${spec.file}`, runA[spec.file], spec)
      const bytesB = assertNonTrivial(`run B / ${spec.file}`, runB[spec.file], spec)
      log(`   non-vacuity ${spec.file}: run A ${bytesA} bytes, run B ${bytesB} bytes (floor ${spec.minBytes}, all markers present)`)

      const det = compare(runA[spec.file], runB[spec.file])
      if (!det.identical) {
        err(
          `\n❌ NON-DETERMINISTIC GENERATOR: two runs of scripts/generate-validators.mjs produced different ${spec.file}.\n\n` +
            `   First divergence at byte ${det.index}:\n` +
            `     run A: ...${JSON.stringify(det.aContext)}\n` +
            `     run B: ...${JSON.stringify(det.bContext)}\n\n` +
            `   ${spec.file} is COMMITTED and regenerated by every \`npm run build\`, so a varying\n` +
            `   byte leaves the working tree dirty on every build and destroys \`git status\` as a\n` +
            `   verification signal. This is exactly the defect the \`Generated at:\` timestamp\n` +
            `   caused before 2026-08-29.\n\n` +
            `   Fix: remove the clock / PID / random / absolute-path input from the emitted bytes.\n`,
        )
        return 1
      }
      log(`✅ determinism ${spec.file}: two independent runs byte-identical`)
    }

    // ── 3. Freshness: the committed artefact must match ───────────────────
    for (const spec of ARTEFACTS) {
      const committedPath = path.join(committedDir, spec.file)
      if (!existsSync(committedPath)) {
        err(`\n❌ ${path.relative(ROOT, committedPath)} is MISSING. It is committed on purpose — src/poc/io/validate.ts imports it, and that import is reached from vitest where no generation step runs.\n\n   Fix: pnpm run generate:validators\n`)
        return 1
      }
      const committed = readFileSync(committedPath, 'utf8')
      assertNonTrivial(`committed / ${spec.file}`, committed, spec)

      const fresh = compare(runA[spec.file], committed)
      if (!fresh.identical) {
        err(
          `\n❌ STALE ARTEFACT: ${path.relative(ROOT, committedPath)} differs from what the generator produces.\n\n` +
            `   First divergence at byte ${fresh.index}:\n` +
            `     generated: ...${JSON.stringify(fresh.aContext)}\n` +
            `     committed: ...${JSON.stringify(fresh.bContext)}\n\n` +
            `   The generator is deterministic (proven above), so this is real drift — a schema\n` +
            `   edit, an Ajv upgrade or a generator-options change that was not committed. This\n` +
            `   check is what replaced the \`Generated at:\` stamp: the stamp only ASSERTED\n` +
            `   freshness, this one measures it.\n\n` +
            `   Fix: pnpm run generate:validators && git add src/generated\n`,
        )
        return 1
      }
      log(`✅ freshness ${spec.file}: committed artefact matches a fresh generation`)
    }

    log('\n✅ Generated validators are deterministic and up to date.')
    return 0
  } catch (e) {
    if (e instanceof VacuousOutputError) {
      err(`\n❌ VACUOUS OUTPUT — the comparison could not be trusted, so no verdict was issued.\n\n   ${e.message}\n\n   An empty or truncated generation compares EQUAL to another empty or truncated\n   generation. Agreement between two nothings is not evidence. Treated as a hard\n   failure on purpose.\n`)
      return 1
    }
    err(`\n❌ ${e && e.stack ? e.stack : e}\n`)
    return 1
  } finally {
    for (const d of dirs) {
      try {
        rmSync(d, { recursive: true, force: true })
      } catch {
        /* best effort */
      }
    }
  }
}

// Only run when invoked directly, so the controls spec can import the pieces.
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  process.exit(run())
}
